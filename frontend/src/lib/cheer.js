export function cheerLine(cardId, name, dateKey) {
  const list = CHEER[cardId] || CHEER[17];
  let h = 0;
  for (const ch of `${cardId}${dateKey || ''}`) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  const line = list[h % list.length];
  const n = (name || '').trim();
  return n ? `${n}님, ${line}` : line;
}
